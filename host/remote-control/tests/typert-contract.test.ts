import test from 'node:test'
import assert from 'node:assert/strict'
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { checkTypertContracts } from '../../../tools/typert-contract-check.js'

const jsonContract = 'contracts/typert/native-api.json'
const kotlinContract = 'android/core/protocol/src/main/kotlin/cn/edu/ustc/tokenworks/DshNativeTypes.kt'
const generatedJson = JSON.stringify({ dshVersion: '0.2.1-rc.5', methods: { 'session/list': {} } }, null, 2) + '\n'
const generatedKotlin = '// Generated by tools/generate-typert-contract.ts; do not edit.\npackage cn.edu.ustc.tokenworks\n\nobject DshMethods\n'

async function stage(root: string, path: string, content: string): Promise<void> {
  const target = join(root, path)
  await mkdir(dirname(target), { recursive: true })
  await writeFile(target, content)
}

test('typert contract check accepts LF and CRLF-on-disk copies of generated contracts', async () => {
  const root = await mkdtemp(tmpdir() + '/typert check-#中文-')
  try {
    await stage(root, jsonContract, generatedJson.replaceAll('\n', '\r\n'))
    await stage(root, kotlinContract, generatedKotlin.replaceAll('\n', '\r\n'))
    const candidates = [
      { path: jsonContract, content: generatedJson },
      { path: kotlinContract, content: generatedKotlin },
    ]
    await checkTypertContracts(candidates, root)
    await stage(root, jsonContract, generatedJson)
    await stage(root, kotlinContract, generatedKotlin)
    await checkTypertContracts(candidates, root)
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('typert contract check rejects stale JSON and Kotlin content, whitespace edits, BOM, empty and missing files', async () => {
  const root = await mkdtemp(tmpdir() + '/typert check-#中文-')
  try {
    const stale: Array<[string, string]> = [
      [jsonContract, JSON.stringify({ dshVersion: '0.2.1-rc.4', methods: { 'session/list': {} } }, null, 2) + '\n'],
      [jsonContract, generatedJson.replace('0.2.1-rc.5', '0.2.1-rc.5 ')],
      [jsonContract, '\ufeff' + generatedJson],
      [jsonContract, ''],
      [kotlinContract, generatedKotlin.replace('object DshMethods', 'object DshMethodsV2')],
      [kotlinContract, generatedKotlin + '\n'],
      [kotlinContract, ''],
    ]
    for (const [path, content] of stale) {
      await stage(root, path, content)
      await assert.rejects(
        () => checkTypertContracts([{ path, content: path === jsonContract ? generatedJson : generatedKotlin }], root),
        /is stale; run npm run contracts:typert/,
      )
    }
    await rm(join(root, kotlinContract))
    await assert.rejects(
      () => checkTypertContracts([{ path: kotlinContract, content: generatedKotlin }], root),
      /is stale; run npm run contracts:typert/,
    )
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})
